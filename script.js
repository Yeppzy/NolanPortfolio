function syncThemeButton() {
  const isLight = document.body.classList.contains('light-theme')
  const isRed = document.body.classList.contains('red-theme')
  themeButton?.setAttribute('aria-pressed', String(isLight || isRed))
  if (themeButton) {
    const label = isLight ? 'Red' : isRed ? 'Dark' : 'Light'
    const language = localStorage.getItem('nolan-language') || 'en'
    themeButton.textContent = translations?.[language]?.[label] || label
  }
}

themeButton?.addEventListener('click', () => {
  const isLight = document.body.classList.contains('light-theme')
  const isRed = document.body.classList.contains('red-theme')

  document.body.classList.remove('light-theme', 'red-theme')

  if (!isLight && !isRed) {
    document.body.classList.add('light-theme')
    localStorage.setItem('nolan-theme', 'light')
  } else if (isLight) {
    document.body.classList.add('red-theme')
    localStorage.setItem('nolan-theme', 'red')
  } else {
    localStorage.setItem('nolan-theme', 'dark')
  }

  syncThemeButton()
})

