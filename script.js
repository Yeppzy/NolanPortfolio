const imageExtensions = ['webp', 'jpg', 'jpeg', 'png', 'avif']
const mediaVersion = Date.now().toString(36)

function versionedMediaPath(source) {
  if (!source || source.startsWith('data:') || source.includes('?v=')) return source
  return `${source}?v=${mediaVersion}`
}

function imageBaseName(image) {
  return image.replace(/\.[^.]+$/, '')
}

function imageCandidates(image, extensions = imageExtensions) {
  const base = imageBaseName(image)
  const currentExtension = image.split('.').pop()?.toLowerCase()
  const candidates = [currentExtension, ...extensions].filter(Boolean)
  return [...new Set(candidates)].map((extension) => `assets/photos/${base}.${extension}`)
}

function renderImageTag(image, alt, className = '', extensions = imageExtensions) {
  const candidates = imageCandidates(image, extensions)
  return `<img${className ? ` class="${className}"` : ''} src="${versionedMediaPath(candidates[0])}" data-src-base="${imageBaseName(image)}" data-src-extensions="${extensions.join(',')}" data-src-index="0" alt="${alt}" />`
}

function expandedProjectImages(project) {
  const images = [...project.images]
  if (project.imagePrefix) {
    const escapedPrefix = project.imagePrefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const numberPattern = new RegExp(`^${escapedPrefix} (\\d+)\\.[^.]+$`)
    const highestNumber = project.images.reduce((highest, image) => {
      const match = image.match(numberPattern)
      return match ? Math.max(highest, Number(match[1])) : highest
    }, 0)
    const lastNumberToTry = highestNumber + (project.imageLookahead || 20)
    for (let index = highestNumber + 1; index <= lastNumberToTry; index += 1) {
      images.push(`${project.imagePrefix} ${index}.webp`)
    }
  }
  const seen = new Set()
  return images.filter((image) => {
    const base = imageBaseName(image)
    if (seen.has(base)) return false
    seen.add(base)
    return true
  })
}

function renderGalleryImage(project, image, index, galleryClass, isGeneratedImage = false) {
  const isProgressImage = project.progressImage === image
  const isSoftBackdrop = project.title === 'Studio Flow' && ['Studio Flow 3', 'Studio Flow 4'].includes(imageBaseName(image))
  const extensions = isGeneratedImage ? ['webp'] : imageExtensions
  const progressStyle = isProgressImage ? ` style="--progress: ${project.progressValue}"` : ''
  const imageMarkup = isProgressImage
    ? `
              <div class="progress-photo"${progressStyle} data-cursor="sharp">
                ${renderImageTag(image, `${project.title} image ${index + 1}`, 'bw-layer', extensions)}
                ${renderImageTag(image, '', 'color-layer', extensions)}
                <span>${project.progressValue}</span>
              </div>
            `
    : `
              <div class="work-image free${isSoftBackdrop ? ' is-soft-backdrop' : ''}" data-cursor="sharp">
                ${renderImageTag(image, `${project.title} image ${index + 1}`, '', extensions)}
              </div>
            `

  return `
            <figure class="gallery-item ${galleryClass}" data-optional-image>
${imageMarkup}
            </figure>
          `
}

function renderProjectPage() {
  const root = document.querySelector('[data-project-root]')
  const projectKey = document.body.dataset.project
  const project = projects[projectKey]

  if (!root || !project) return

  const galleryClasses = ['giant', '', 'wide', 'tall', '', 'wide', '', 'giant', '', 'tall', 'wide', '']
  const currentIndex = projectOrder.indexOf(projectKey)
  const previousProject = projects[projectOrder[(currentIndex - 1 + projectOrder.length) % projectOrder.length]]
  const nextProject = projects[projectOrder[(currentIndex + 1) % projectOrder.length]]

  root.insertAdjacentHTML('beforebegin', header)
  root.innerHTML = `
    <section class="detail-hero bleed">
      <p class="eyebrow">${project.category}</p>
      <h1 data-cursor="blur">${project.title}</h1>
    </section>

    <section class="detail-intro bleed">
      <div class="detail-meta">
        <span>${project.number}</span>
        <span>${project.year}</span>
        <span>${project.category}</span>
      </div>
      <p>${project.description}</p>
    </section>

    <section class="project-gallery bleed" aria-label="${project.title} gallery">
      ${expandedProjectImages(project)
        .map((image, index) =>
          renderGalleryImage(
            project,
            image,
            index,
            galleryClasses[index % galleryClasses.length],
            index >= project.images.length,
          ),
        )
        .join('')}
    </section>

    ${
      project.externalLink
        ? `<section class="project-external bleed">
            <a class="text-link" href="${project.externalLink}" target="_blank" rel="noreferrer">${project.externalLabel}</a>
            <p>${project.externalNote}</p>
          </section>`
        : ''
    }

    <section class="project-nav bleed" aria-label="Next and previous projects">
      <a href="${previousProject.href}" class="project-nav-card">
        <span>Previous project</span>
        <figure class="work-image" data-cursor="sharp">
          ${renderImageTag(previousProject.mainImage, previousProject.title)}
        </figure>
        <strong>${previousProject.title}</strong>
      </a>
      <a href="${nextProject.href}" class="project-nav-card">
        <span>Next project</span>
        <figure class="work-image" data-cursor="sharp">
          ${renderImageTag(nextProject.mainImage, nextProject.title)}
        </figure>
        <strong>${nextProject.title}</strong>
      </a>
    </section>
  `
  root.insertAdjacentHTML('afterend', footer)
}

