const normalizedSpeed = Math.min(speed / maxSpeed, 1)
const currentSize = maxSize - (maxSize - minSize) * normalizedSpeed

cursor.style.width = `${currentSize}px`
cursor.style.height = `${currentSize}px`
  const wasBlur = cursor.classList.contains('is-blur')
const isBlur = Boolean(blurTarget)

