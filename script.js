const languages = ['en', 'sk', 'ja']
let currentLanguage = localStorage.getItem('nolan-language') || 'en'

function applyLanguage(language) {
  currentLanguage = language
  document.documentElement.lang = language
  langButton.textContent = language.toUpperCase()
  localStorage.setItem('nolan-language', language)

  syncThemeButton()

  document.querySelectorAll('[data-i18n="landing-name"]').forEach((node) => {
    const values = {
      en: 'NOLAN MATÚŠ<br />WILLEMS',
      sk: 'NOLAN MATÚŠ<br />WILLEMS',
      ja: 'ノラン マトゥーシュ<br />ウィレムス',
    }
    node.innerHTML = values[language] || values.en
  })

  document.querySelectorAll('a, p, span, strong, h1, h2, small, em').forEach((node) => {
    if (node.dataset.i18n === 'landing-name') return
    const original = node.dataset.originalText || node.textContent.trim()
    if (!original) return
    node.dataset.originalText = original
    const translated = translations[language]?.[original]
    if (translated) {
      node.textContent = translated
      node.dataset.translated = 'true'
    } else if (node.dataset.translated === 'true') {
      node.textContent = original
      delete node.dataset.translated
    }
  })
}

